#!/usr/bin/env python3
"""Measure sign/verify and ledger append timings (N=64) for evidence docs."""

from __future__ import annotations

import statistics
import tempfile
import time
from pathlib import Path

N = 64
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "EVIDENCE_BENCHMARK.md"


def _ms(samples: list[float]) -> dict[str, float]:
    return {
        "n": float(len(samples)),
        "mean_ms": statistics.mean(samples) * 1000.0,
        "p50_ms": statistics.median(samples) * 1000.0,
        "max_ms": max(samples) * 1000.0,
    }


def main() -> None:
    from matrixscroll import sign_manifest, verify_manifest
    from matrixscroll.ledger import Ledger, verify_chain

    with tempfile.TemporaryDirectory() as tmp:
        import os

        os.environ["MATRIXSCROLL_HOME"] = tmp
        # Fresh identity under temp home.
        from matrixscroll.providers.registry import get_provider

        get_provider()  # ensure device exists

        sign_samples: list[float] = []
        verify_samples: list[float] = []
        for i in range(N):
            body = {"bench": True, "i": i}
            t0 = time.perf_counter()
            signed = sign_manifest(body)
            sign_samples.append(time.perf_counter() - t0)
            t1 = time.perf_counter()
            ok = verify_manifest(signed)
            verify_samples.append(time.perf_counter() - t1)
            assert ok is True

        ledger = Ledger()
        append_samples: list[float] = []
        for i in range(N):
            t0 = time.perf_counter()
            ledger.append({"i": i, "payload": f"row-{i}"})
            append_samples.append(time.perf_counter() - t0)
        t0 = time.perf_counter()
        verdict = verify_chain(ledger.records)
        chain_ms = (time.perf_counter() - t0) * 1000.0
        assert verdict.name == "CONSISTENT"

    sign_stats = _ms(sign_samples)
    verify_stats = _ms(verify_samples)
    append_stats = _ms(append_samples)

    lines = [
        "# Evidence benchmark (local)",
        "",
        "Generated by `scripts/evidence_benchmark.py`. Timings are host-local",
        "and not a certification claim. Re-run on your hardware before quoting",
        "numbers in a proposal.",
        "",
        f"N = {N}",
        "",
        "| Operation | mean (ms) | p50 (ms) | max (ms) |",
        "| --- | ---: | ---: | ---: |",
        f"| sign_manifest | {sign_stats['mean_ms']:.3f} | {sign_stats['p50_ms']:.3f} | {sign_stats['max_ms']:.3f} |",
        f"| verify_manifest | {verify_stats['mean_ms']:.3f} | {verify_stats['p50_ms']:.3f} | {verify_stats['max_ms']:.3f} |",
        f"| ledger.append | {append_stats['mean_ms']:.3f} | {append_stats['p50_ms']:.3f} | {append_stats['max_ms']:.3f} |",
        f"| verify_chain (N={N}) | {chain_ms:.3f} | - | - |",
        "",
        "Environment: Python `matrixscroll` emulated Ed25519 under a temporary",
        "`MATRIXSCROLL_HOME`.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")
    print(
        __import__("json").dumps(
            {
                "sign": sign_stats,
                "verify": verify_stats,
                "append": append_stats,
                "verify_chain_ms": chain_ms,
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
